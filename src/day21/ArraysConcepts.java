package day21;

public class ArraysConcepts {
    static void main() {


        //45,67,78,98,23,45,66 : multiple values of SIMILAR data type

        //dataType name = value;
        int age = 44;

        //Ashish
        String name = "Ashish";

        System.out.println(age);

        //dataType[] name = {value1, value2, value3.........};

        int[] marks = {45, 67, 78, 98, 23, 45, 66};
        System.out.println(marks[0]);
        System.out.println(marks[1]);
        System.out.println(marks[2]);
        System.out.println(marks[3]);
        System.out.println(marks[4]);
        System.out.println(marks[5]);

        System.out.println("================================");
        //Leon, Naoufel, Lee, Kerrie, Lisa, Mike

        String[] students = {"Leon", "Naoufel", "Lee", "Kerrie", "Lisa", "Mike"};
        System.out.println(students[0]);
        System.out.println(students[1]);
        System.out.println(students[2]);
        System.out.println(students[3]);
        System.out.println(students[4]);
        System.out.println(students[5]);

        System.out.println("===============================");
        // 12.34, 45.67, 67.89, 12.33
        double[] temp = {12.34, 45.67, 67.89, 12.33};
        System.out.println(temp[0]);
        System.out.println(temp[1]);
        System.out.println(temp[2]);
        System.out.println(temp[3]);


        System.out.println("===============================");
        // Jason, 34, 5.9, false, 'm'



    }
}
